/**
 * The Custom theme end to end (`docs/specs/ui/design-language.md` §2,
 * "Custom"): a record stored in the key-value store as the app writes it is
 * read by the theme provider, a control on the editor's page is moved and let
 * go, and the record the save writes is what the app then draws. Each block
 * proves one rule of the chart ramp's ends and Solid bars, the three inks,
 * Borders or the full colour range, through that whole path: the roles the
 * provider hands every screen (`useUiRoles`), the bar fills (`useBarFills`)
 * and, for Solid bars, real bar marks. The last block proves that a theme
 * stored before those parts existed draws byte-identical roles to the ones
 * that build drew (`fixtures/custom-before-inks-borders-ramp-roles.json`,
 * generated by it) until one of the new controls is moved. The per-rule
 * detail lives in `ui-theme-custom.test.ts` and `theme-custom-screen.test.tsx`.
 * Replaced, as there: the log sink and expo-router's params and stack
 * options; a slider is let go by calling the handler the gesture-handler stub
 * kept.
 */

jest.mock('@/src/logging/logEvent', () => ({ logEvent: jest.fn() }));

let mockPart = 'background';
jest.mock('expo-router', () => ({
  useLocalSearchParams: () => ({ part: mockPart }),
  useRouter: () => ({ setParams: jest.fn() }),
  Stack: { Screen: () => null },
}));

import { act, fireEvent, screen, waitFor } from '@testing-library/react-native';
import { Storage } from 'expo-sqlite/kv-store';
import { Text } from 'react-native';

import { ShareBar } from '@/components/today/week-figures';
import { hexToLch, lchToHex } from '@/components/ui/lch';
import { washLightness, type UiRoles } from '@/components/ui/theme';
import { useBarFills, useUiRoles, type BarFills } from '@/components/ui/theme-context';
import { GAMUT_SCALE, hueTurn, parseCustomColours, type CustomColours } from '@/components/ui/theme-custom';
import { APPEARANCE_STORAGE_KEY } from '@/components/ui/theme-launch';
import { appearanceMode, appearanceRoles } from '@/components/ui/theme-presets';
import { parseAppearanceRecord } from '@/components/ui/theme-record';
import ThemeCustomRoute from '../app/theme-custom';
import BEFORE_INKS_BORDERS_RAMP from './fixtures/custom-before-inks-borders-ramp-roles.json';
import { renderWithTheme } from './helpers/theme';

// A theme on the gamut scale with every new part stored: its own inks and
// ramp.
const CUSTOM: CustomColours = {
  scale: GAMUT_SCALE,
  background: { hue: 80, strength: 20, mode: 'light', lightness: 90, depth: 100, borders: 100 },
  ink: { hue: 265, strength: 30, lightness: 8 },
  text: { hue: 60, strength: 10, contrast: 100 },
  secondary: { hue: 200, strength: 20, lightness: 45 },
  muted: { hue: 120, strength: 30, lightness: 60 },
  accent: { hue: 30, strength: 70 },
  highlight: { hue: 300, strength: 40, match: false, contrast: 100 },
  record: { hue: 90, strength: 50 },
  chart: { follow: false, solid: false, start: { hue: 200, strength: 30, lightness: 85 }, end: { hue: 320, strength: 80, lightness: 40 } },
  direction: 'green-crimson',
};

type DrawnState = { roles: UiRoles; bars: BarFills };

// What the app draws: every role the provider hands a screen, and the bar fills.
function Drawn() {
  const roles = useUiRoles();
  const bars = useBarFills();
  return <Text testID="drawn">{JSON.stringify({ roles, bars })}</Text>;
}
const drawn = (): DrawnState => JSON.parse(screen.getByTestId('drawn').props.children);

const storeRecord = (record: string) => Storage.setItemSync(APPEARANCE_STORAGE_KEY, record);
const store = (custom: unknown) => storeRecord(JSON.stringify({ theme: 'custom', mode: 'light', custom }));
const storedRecord = (): string => Storage.getItemSync(APPEARANCE_STORAGE_KEY)!;
const stored = (): Record<string, unknown> => JSON.parse(storedRecord()).custom;
// The roles the stored record draws, read as the app reads it at launch.
const rolesOfRecord = (record: string): UiRoles => {
  const { appearance } = parseAppearanceRecord(record);
  return appearanceRoles(appearance!, appearanceMode(appearance!, null));
};

// The app with the editor's page for a part open on top, as the stack draws it.
function openEditor(part: string, below?: React.ReactElement) {
  mockPart = part;
  return renderWithTheme(
    <>
      <Drawn />
      {below}
      <ThemeCustomRoute />
    </>,
  );
}

type Handlers = { onEnd: (event: { x: number }, success: boolean) => void };
const slider = (name: string) => screen.getByRole('adjustable', { name });
// Lets a slider go at a value: a tap on a track laid out one point per unit.
async function letGo(name: string, testID: string, value: number, [min, max]: [number, number]) {
  fireEvent(screen.getByTestId(`${testID}-track`), 'layout', { nativeEvent: { layout: { width: max - min } } });
  const before = storedRecord();
  await act(async () => (slider(name).props.gesture.gestures[1].handlers as Handlers).onEnd({ x: value - min }, true));
  await waitFor(() => expect(storedRecord()).not.toBe(before));
}
async function flip(name: string) {
  const before = storedRecord();
  await act(async () => fireEvent.press(screen.getByRole('switch', { name })));
  await waitFor(() => expect(storedRecord()).not.toBe(before));
}
// The app has repainted in what the save wrote.
const repainted = () => waitFor(() => expect(drawn().roles).toEqual(rolesOfRecord(storedRecord())));

// The roles that differ between two drawings.
const changed = (before: UiRoles, after: UiRoles): string[] =>
  (Object.keys(after) as (keyof UiRoles)[]).filter((role) => after[role] !== before[role]).sort();

// An LCh step between two colours, in a share of the way.
const between = (from: string, to: string, share: number, turn: number) => {
  const [a, b] = [hexToLch(from), hexToLch(to)];
  return {
    lightness: a.lightness + share * (b.lightness - a.lightness),
    chroma: a.chroma + share * (b.chroma - a.chroma),
    hue: (((a.hue + share * turn) % 360) + 360) % 360,
  };
};
const near = (actual: string, expected: { lightness: number; chroma: number; hue: number }) => {
  const lch = hexToLch(actual);
  expect(Math.abs(lch.lightness - expected.lightness)).toBeLessThan(1);
  expect(Math.abs(lch.chroma - expected.chroma)).toBeLessThan(1.5);
  expect(Math.abs(hueTurn(expected.hue, lch.hue))).toBeLessThan(2);
};

describe('the chart ramp’s ends and Solid bars', () => {
  it('draws the ramp from the start and end let go, the steps between at the LCh thirds the short way round', async () => {
    store(CUSTOM);
    openEditor('chart');
    await letGo('End lightness', 'theme-custom-end-lightness', 30, [0, 100]);
    await letGo('Start hue', 'theme-custom-start-hue', 10, [0, 359]);
    await repainted();

    const { chart } = stored() as CustomColours;
    expect(chart).toEqual({ ...CUSTOM.chart, start: { ...CUSTOM.chart!.start, hue: 10 }, end: { ...CUSTOM.chart!.end, lightness: 30 } });
    const { viz1, viz2, viz3, viz4 } = drawn().roles;
    expect(Math.round(hexToLch(viz1).lightness)).toBe(85);
    expect(Math.round(hexToLch(viz4).lightness)).toBe(30);
    // From 10° to 320° the short way is down through 0°: −50°.
    near(viz2, between(viz1, viz4, 1 / 3, -50));
    near(viz3, between(viz1, viz4, 2 / 3, -50));
    expect(hexToLch(viz2).hue).toBeGreaterThan(340);
  });

  it('starts from the page’s ramp, and leaving it moves neither end', async () => {
    const { chart: _chart, ...followed } = CUSTOM;
    store(followed);
    openEditor('chart');
    const before = drawn().roles;
    await flip('Follow background');
    await repainted();
    expect([drawn().roles.viz1, drawn().roles.viz4]).toEqual([before.viz1, before.viz4]);
  });

  // [[appearance.solid-bars]]
  it('draws the bar marks as Solid bars says, on and off again', async () => {
    store(CUSTOM);
    openEditor('chart', <ShareBar current={5} previous={2} testID="laps" />);
    const { viz3, viz4 } = drawn().roles;
    expect(viz3).not.toBe(viz4);
    // A third lap over the second's full `viz3`, in `viz4`.
    expect(screen.getByTestId('laps')).toHaveStyle({ backgroundColor: viz3 });

    await flip('Solid bars');
    await repainted();
    expect(stored().chart).toMatchObject({ solid: true });
    expect(drawn().bars).toEqual({ viz2: viz4, viz3: viz4, viz4 });
    expect(screen.getByTestId('laps')).toHaveStyle({ backgroundColor: viz4 });
    expect(screen.getByTestId('laps-fill')).toHaveStyle({ backgroundColor: viz4, width: '50%' });
    expect(drawn().roles.viz3).toBe(viz3);

    await flip('Solid bars');
    await waitFor(() => expect(drawn().bars.viz3).toBe(viz3));
    expect(screen.getByTestId('laps')).toHaveStyle({ backgroundColor: viz3 });
  });
});

describe('three inks, each its own', () => {
  const INKS = ['ink', 'inkMuted', 'inkFaint'] as const;
  const { secondary: _secondary, muted: _muted, ...STEPPED } = CUSTOM;

  it.each([
    ['ink', 'Lightness', 'theme-custom-lightness', 30, [0, 40], ['ink', 'pageInk', 'scrim']],
    ['secondary', 'Lightness', 'theme-custom-lightness', 70, [0, 100], ['inkMuted', 'pageInkMuted']],
    ['muted', 'Hue', 'theme-custom-hue', 10, [0, 359], ['inkFaint', 'pageInkFaint']],
  ] as const)('moves only the %s’s roles when its %s is let go', async (part, name, testID, value, range, roles) => {
    store(CUSTOM);
    openEditor(part);
    const before = drawn().roles;
    await letGo(name, testID, value, [...range]);
    await repainted();
    expect(changed(before, drawn().roles)).toEqual([...roles].sort());
  });

  it('stores the secondary and the muted text as drawn on the first move of either, so neither jumps', async () => {
    store(STEPPED);
    openEditor('secondary');
    const before = drawn().roles;
    await letGo('Lightness', 'theme-custom-lightness', 30, [0, 100]);
    await repainted();
    expect(stored()).toHaveProperty('muted');
    expect(changed(before, drawn().roles)).toEqual(['inkMuted', 'pageInkMuted']);
    expect(Math.round(hexToLch(drawn().roles.inkMuted).lightness)).toBe(30);
  });

  it('keeps no gap between them: secondary text may sit past the primary, and muted text on it', async () => {
    store(CUSTOM);
    openEditor('secondary');
    await letGo('Lightness', 'theme-custom-lightness', 0, [0, 100]);
    await repainted();
    screen.unmount();
    openEditor('muted');
    await letGo('Lightness', 'theme-custom-lightness', 8, [0, 100]);
    await repainted();
    const [ink, inkMuted, inkFaint] = INKS.map((role) => hexToLch(drawn().roles[role]).lightness);
    expect(inkMuted).toBeLessThan(ink);
    expect(Math.abs(inkFaint - ink)).toBeLessThan(0.5);
  });
});

describe('Borders apart from Depth', () => {
  const HAIRLINES = ['rule', 'ruleSoft'];
  const GROUNDS = ['raised', 'surface', 'viz0', 'well'];

  it('moves only the hairlines with Borders, and only the grounds with Depth', async () => {
    store(CUSTOM);
    openEditor('background');
    const start = drawn().roles;
    await letGo('Borders', 'theme-custom-borders', 300, [0, 300]);
    await repainted();
    const bordered = drawn().roles;
    expect(changed(start, bordered)).toEqual(HAIRLINES);

    await letGo('Depth', 'theme-custom-depth', 0, [0, 300]);
    await repainted();
    // With no depth the grounds and empty cells lie on the page itself.
    expect(changed(bordered, drawn().roles)).toEqual(GROUNDS);
    GROUNDS.forEach((role) => expect(Math.abs(hexToLch(drawn().roles[role as keyof UiRoles]).lightness - 90)).toBeLessThan(0.5));
    expect(HAIRLINES.map((role) => drawn().roles[role as keyof UiRoles])).toEqual(HAIRLINES.map((role) => bordered[role as keyof UiRoles]));
  });
});

describe('the full colour range', () => {
  // Whether sRGB holds a colour: drawn, it keeps its chroma.
  const holds = (lightness: number, chroma: number, hue: number) => hexToLch(lchToHex({ lightness, chroma, hue })).chroma > chroma - 0.5;

  it.each([
    ['background', 'Strength', 'theme-custom-strength', 'paper'],
    ['ink', 'Strength', 'theme-custom-strength', 'ink'],
    ['secondary', 'Strength', 'theme-custom-strength', 'inkMuted'],
    ['muted', 'Strength', 'theme-custom-strength', 'inkFaint'],
    ['accent', 'Strength', 'theme-custom-strength', 'accent'],
    ['highlight', 'Strength', 'theme-custom-strength', 'accentWash'],
    ['record', 'Strength', 'theme-custom-strength', 'record'],
    ['chart', 'Start strength', 'theme-custom-start-strength', 'viz1'],
    ['chart', 'End strength', 'theme-custom-end-strength', 'viz4'],
  ] as const)('draws the %s’s %s as a share of the most chroma its hue holds at its L*', async (part, name, testID, role) => {
    store(CUSTOM);
    openEditor(part);
    await letGo(name, testID, 100, [0, 100]);
    await repainted();
    const full = hexToLch(drawn().roles[role]);
    // The highlight is a share at its ladder's wash L*, then moved onto the
    // page by its contrast, chroma kept.
    const at = part === 'highlight' ? washLightness('light') : full.lightness;
    expect(holds(at, full.chroma + 3, full.hue)).toBe(false);

    await letGo(name, testID, 50, [0, 100]);
    await repainted();
    expect(Math.abs(hexToLch(drawn().roles[role]).chroma - full.chroma / 2)).toBeLessThan(1);
  });

  it.each([
    ['accent', 'accent', 30],
    ['record', 'record', 55],
  ] as const)('lets the %s be a bright red or orange with its Lightness', async (part, role, hue) => {
    store({ ...CUSTOM, [part]: { hue, strength: 100 } });
    openEditor(part);
    await letGo('Lightness', 'theme-custom-lightness', 62, [0, 100]);
    await repainted();
    const { lightness, chroma } = hexToLch(drawn().roles[role]);
    expect(Math.round(lightness)).toBe(62);
    // Far more than a preset's accent holds at its L* 43 (Warm's: 63).
    expect(chroma).toBeGreaterThan(65);
    expect(stored()[part]).toEqual({ hue, strength: 100, lightness: 62 });
  });
});

describe('a theme stored before the inks, borders, chart and gamut scale', () => {
  const CASES: { stored: string; roles: UiRoles }[] = BEFORE_INKS_BORDERS_RAMP.cases;

  it('reads every such record, and draws every role byte-identical to that build', () => {
    expect(CASES.length).toBeGreaterThan(40);
    const drift = CASES.filter(({ stored: record, roles }) => JSON.stringify(rolesOfRecord(record)) !== JSON.stringify(roles));
    expect(drift.map(({ stored: record }) => record)).toEqual([]);
  });

  it('is drawn so by the app, with the bars in their steps', () => {
    CASES.forEach(({ stored: record, roles }) => {
      storeRecord(record);
      const { unmount } = renderWithTheme(<Drawn />);
      expect(JSON.stringify(drawn().roles)).toBe(JSON.stringify(roles));
      expect(drawn().bars).toMatchObject({ viz2: roles.viz2, viz3: roles.viz3, viz4: roles.viz4 });
      unmount();
    });
  });

  // A record from then with every old control moved off its default, none to
  // an end: Slate on a tinted light page at L* 81.75, depth 40, its own
  // highlight.
  const [{ stored: RECORD, roles: ROLES }] = CASES.filter(({ stored: record }) => {
    const { background, highlight } = JSON.parse(record).custom;
    return background.lightness === 81.75 && highlight?.match === false;
  });

  it('stays as stored, and drawn, while only the old controls are moved', async () => {
    storeRecord(RECORD);
    openEditor('record');
    await letGo('Hue', 'theme-custom-hue', 140, [0, 359]);
    await repainted();
    const custom = stored();
    expect(Object.keys(custom).sort()).toEqual(Object.keys(JSON.parse(RECORD).custom).sort());
    expect(changed(ROLES, drawn().roles)).toEqual(['record', 'recordRule', 'recordWash']);
  });

  it.each([
    ['background', 'Borders', 'theme-custom-borders', 200, [0, 300], ['rule', 'ruleSoft'], 'background.borders'],
    ['secondary', 'Lightness', 'theme-custom-lightness', 50, [0, 100], ['inkMuted', 'pageInkMuted'], 'secondary'],
    ['accent', 'Lightness', 'theme-custom-lightness', 60, [0, 100], ['accent'], 'scale'],
    ['chart', 'End lightness', 'theme-custom-end-lightness', 20, [0, 100], ['viz2', 'viz3', 'viz4'], 'chart'],
  ] as const)(
    'is converted on the first move of the %s’s %s, moving only its roles',
    async (part, name, testID, value, range, roles, field) => {
      storeRecord(RECORD);
      openEditor(part);
      if (part === 'chart') {
        // Leaving the page's ramp keeps both ends; the steps between become
        // the LCh thirds.
        await flip('Follow background');
        await repainted();
        expect(changed(ROLES, drawn().roles)).toEqual(['viz2', 'viz3']);
      }
      await letGo(name, testID, value, [...range]);
      await repainted();
      expect(stored()).toHaveProperty(field);
      expect(parseCustomColours(stored())).not.toBeNull();
      expect(changed(ROLES, drawn().roles)).toEqual([...roles].sort());
    },
  );
});
